const output=await mkdtemp(join(tmpdir(),'switchboard-explorer-check-'));
const chrome=process.env.CHROME_BIN||'/usr/bin/google-chrome';
await access(chrome);
const browser=spawn(chrome,['--headless=new','--no-sandbox','--disable-dev-shm-usage','--disable-gpu','--no-first-run','--no-default-browser-check','--remote-debugging-pipe',`--user-data-dir=${join(output,'profile')}`],{stdio:['ignore','ignore','pipe','pipe','pipe']});
let stderr='',serial=0,session,buffer='';
const requests=new Map(),events=[],errors=[];
browser.stderr.on('data',b=>stderr+=b.toString());
browser.stdio[3].on('error',()=>{});
browser.stdio[4].on('error',()=>{});
browser.on('exit',code=>{if(code){console.error(`Chromium exited ${code}: ${stderr}`);}});
browser.stdio[4].on('data',chunk=>{
  buffer+=chunk.toString();
  while(buffer.includes('\0')){
    const at=buffer.indexOf('\0'),raw=buffer.slice(0,at);buffer=buffer.slice(at+1);
    if(!raw)continue;
    const message=JSON.parse(raw);
    if(message.id){const task=requests.get(message.id);if(task){requests.delete(message.id);clearTimeout(task.timeout);message.error?task.reject(new Error(JSON.stringify(message.error))):task.resolve(message.result);}}
    else {events.push(message);if(message.method==='Runtime.exceptionThrown')errors.push(message.params.exceptionDetails);}
  }
});
function call(method,params={},sessionId=session){
  return new Promise((resolve,reject)=>{
    const id=++serial,timeout=setTimeout(()=>{requests.delete(id);reject(new Error(`Timed out: ${method}\n${stderr.slice(-2500)}`));},15000);
    requests.set(id,{resolve,reject,timeout});
    browser.stdio[3].write(JSON.stringify({id,method,params,...(sessionId?{sessionId}:{})})+'\0');
  });
}
async function evaluate(expression){
  const r=await call('Runtime.evaluate',{expression,returnByValue:true,awaitPromise:true});
  if(r.exceptionDetails)throw new Error(JSON.stringify(r.exceptionDetails));
  return r.result.value;
}
const pause=ms=>new Promise(r=>setTimeout(r,ms));
async function click(selector){
  const point=await evaluate(`(()=>{const e=document.querySelector(${JSON.stringify(selector)});if(!e)throw Error('Missing click target');e.scrollIntoView({block:'center'});const r=e.getBoundingClientRect();return{x:r.x+r.width/2,y:r.y+r.height/2};})()`);
  await call('Input.dispatchMouseEvent',{type:'mousePressed',button:'left',clickCount:1,...point});
  await call('Input.dispatchMouseEvent',{type:'mouseReleased',button:'left',clickCount:1,...point});
}
async function screenshot(name){
  await pause(300); // Let the short section-entry transition finish.
  const r=await call('Page.captureScreenshot',{format:'png',captureBeyondViewport:false});
  await writeFile(join(output,`${name}.png`),Buffer.from(r.data,'base64'));
}
